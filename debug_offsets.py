def main():
    debug_log("Starting offset debug test...")
    
    # Test basic connection
    gmod_exe = test_basic_connection()
    if not gmod_exe:
        debug_log("CRITICAL: Cannot connect to gmod.exe. Make sure the game is running.")
        return
    
    # Test modules
    modules = test_modules(gmod_exe)
    if not modules:
        debug_log("CRITICAL: Cannot find required DLL modules.")
        return
    
    # Test offsets
    offset_results = test_offsets(gmod_exe, modules)
    
    # Log the generated reference values so they are visible in one place.
    log_generated_reference()
    log_gmod_state_file()
    
    # Summary
    debug_log("=== SUMMARY ===")
    working_offsets = sum(offset_results.values())
    total_offsets = len(offset_results)
    debug_log(f"Working offsets: {working_offsets}/{total_offsets}")
    
    for offset_name, working in offset_results.items():
        status = "WORKING" if working else "FAILED"
        debug_log(f"  {offset_name}: {status}")
    
    debug_log("=== DEBUG COMPLETE ===")
    debug_log("Check debug_log.txt for detailed information")

if __name__ == "__main__":
    main() 
